const UI = {
  toast(message, type = 'info') {
    let container = document.getElementById('toast-container');
    if (!container) {
      container = document.createElement('div');
      container.id = 'toast-container';
      container.className = 'toast-container';
      document.body.appendChild(container);
    }

    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    
    let icon = Icons.info;
    if (type === 'success') icon = Icons.check;
    else if (type === 'error') icon = Icons.warning;
    else if (type === 'warning') icon = Icons.warning;

    toast.innerHTML = `<span class="toast-icon">${icon}</span><span class="toast-message">${this.escapeHtml(message)}</span>`;
    
    container.appendChild(toast);
    
    setTimeout(() => {
      toast.style.opacity = '0';
      setTimeout(() => {
        if (toast.parentElement) container.removeChild(toast);
      }, 300);
    }, 4000);
  },

  confirm(title, message, onConfirm) {
    const modal = document.getElementById('modal-confirm');
    if (!modal) return;
    
    const titleEl = modal.querySelector('.modal-title') || modal.querySelector('h3');
    const msgEl = modal.querySelector('.modal-message') || modal.querySelector('#confirm-msg');
    const confirmBtn = modal.querySelector('.btn-confirm') || modal.querySelector('#confirm-yes');
    
    if (titleEl) titleEl.textContent = title;
    if (msgEl) msgEl.textContent = message;
    
    if (confirmBtn) {
      // Remove old event listeners
      const newBtn = confirmBtn.cloneNode(true);
      confirmBtn.parentNode.replaceChild(newBtn, confirmBtn);
      
      newBtn.addEventListener('click', () => {
        onConfirm();
        this.hideModal('modal-confirm');
      });
    }
    
    this.showModal('modal-confirm');
  },

  showModal(id) {
    const modal = document.getElementById(id);
    if (modal) {
      modal.style.display = 'flex';
      
      // Close on clicking overlay
      modal.onclick = (e) => {
        if (e.target === modal) this.hideModal(id);
      };
      
      // Wire close buttons inside modal
      const closeBtns = modal.querySelectorAll('.modal-close, .btn-cancel');
      closeBtns.forEach(btn => {
        btn.onclick = () => this.hideModal(id);
      });
    }
  },

  hideModal(id) {
    const modal = document.getElementById(id);
    if (modal) modal.style.display = 'none';
  },

  hideAllModals() {
    document.querySelectorAll('.modal-overlay').forEach(m => {
      m.style.display = 'none';
    });
  },

  emptyState(icon, title, message, btnText = '', btnAction = '') {
    const svgIcon = Icons[icon] || Icons.info;
    let html = `
      <div class="empty-state">
        <div class="empty-icon">${svgIcon}</div>
        <h3 class="empty-title">${this.escapeHtml(title)}</h3>
        <p class="empty-text">${this.escapeHtml(message)}</p>
    `;
    if (btnText && btnAction) {
      html += `<button class="btn btn-primary mt-1" onclick="${btnAction}">${this.escapeHtml(btnText)}</button>`;
    }
    html += `</div>`;
    return html;
  },

  escapeHtml(str) {
    if (str === null || str === undefined) return '';
    const div = document.createElement('div');
    div.textContent = str;
    return div.innerHTML;
  },

  formatDate(dateStr) {
    if (!dateStr) return '-';
    try {
      const d = new Date(dateStr);
      return d.toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });
    } catch(e) {
      return dateStr;
    }
  },

  generateId(prefix) {
    const items = prefix === 'STU' ? window.EduResult.state.students :
                  prefix === 'SUB' ? window.EduResult.state.subjects :
                  prefix === 'RES' ? window.EduResult.state.results : [];
    let maxNum = 0;
    items.forEach(item => {
      if (item && item.id) {
        const num = parseInt(item.id.replace(prefix, ''), 10);
        if (!isNaN(num) && num > maxNum) maxNum = num;
      }
    });
    return prefix + String(maxNum + 1).padStart(3, '0');
  },

  setHTML(element, html) {
    if (typeof element === 'string') element = document.getElementById(element);
    if (element) element.innerHTML = html;
  },

  $(id) {
    return document.getElementById(id);
  },

  pagination(currentPage, totalPages, onPageChange) {
    if (totalPages <= 1) return '';
    let html = '<div class="pagination">';
    html += `<button class="page-btn" ${currentPage === 1 ? 'disabled' : ''} onclick="${onPageChange}(${currentPage - 1})">${Icons.chevronLeft}</button>`;
    
    for (let i = 1; i <= totalPages; i++) {
      if (i === 1 || i === totalPages || (i >= currentPage - 1 && i <= currentPage + 1)) {
        html += `<button class="page-btn ${i === currentPage ? 'active' : ''}" onclick="${onPageChange}(${i})">${i}</button>`;
      } else if (i === currentPage - 2 || i === currentPage + 2) {
        html += `<span class="page-dots">...</span>`;
      }
    }
    
    html += `<button class="page-btn" ${currentPage === totalPages ? 'disabled' : ''} onclick="${onPageChange}(${currentPage + 1})">${Icons.chevronRight}</button>`;
    html += '</div>';
    return html;
  },

  formatNumber(num) {
    if (num === null || num === undefined) return '';
    return Number(num).toLocaleString('en-IN');
  },

  getInitials(name) {
    if (!name) return 'U';
    return name.trim().split(/\s+/).map(n => n[0]).join('').toUpperCase().slice(0, 2);
  },

  gradeColor(grade) {
    const colors = {
      'A+': 'text-success', 'A': 'text-success',
      'B': 'text-primary', 'C': 'text-warning',
      'D': 'text-warning', 'E': 'text-danger',
      'F': 'text-danger'
    };
    return colors[grade] || '';
  },

  debounce(fn, delay = 300) {
    let timer;
    return (...args) => {
      clearTimeout(timer);
      timer = setTimeout(() => fn(...args), delay);
    };
  }
};

window.UI = UI;
window.Icons = Icons;
